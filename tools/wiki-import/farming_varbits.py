RANGE = re.compile(r"if \(value >= (\d+) && value <= (\d+)\)")
SINGLE = re.compile(r"if \(value == (\d+)\)")
RET = re.compile(r"return new PatchState\(Produce\.(\w+), CropState\.(\w+), ([^;]+)\);")


def stage(expr, value, stages):
    expr = re.sub(r"Produce\.(\w+)\.getStages\(\)", lambda m: str(stages[m.group(1)]), expr)
    return int(eval(expr.replace("value", str(value)), {"__builtins__": {}}, {}))  # noqa: S307 - plugin source arithmetic only


def produce_stages(path):
    """Produce name -> growth stages (the second number after the item id in Produce.java)."""
    stages = {}
    for m in re.finditer(r"^\t(\w+)\(.*?ItemID\.\w+,\s*(\d+),\s*(\d+)", open(path, encoding="utf-8").read(), re.M):
        stages[m.group(1)] = int(m.group(3))
    return stages


def main(src, out_dir):
    text = open(src, encoding="utf-8").read()
    stages = produce_stages(os.path.join(os.path.dirname(src), "Produce.java"))
    rows = []
    for patch in PATCHES:
        start = text.index("\t%s(Tab." % patch)
        nxt = re.search(r"\n\t[A-Z_]+\(Tab\.", text[start + 5:])
        block = text[start: start + 5 + nxt.start()] if nxt else text[start:]
        first = last = None
        for line in block.splitlines():
            line = line.strip()
            m = RANGE.search(line)
            s = SINGLE.search(line)
            if m:
                first, last = int(m.group(1)), int(m.group(2))
            elif s:
                first = last = int(s.group(1))
            r = RET.search(line)
            if r and first is not None:
                produce, state, expr = r.groups()
                rows.append((patch, first, last, produce, state, stage(expr, first, stages), stage(expr, last, stages)))
                first = last = None
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "farming-varbits.tsv"), "w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write("patch\tfirst\tlast\tproduce\tstate\tstage_first\tstage_last\n")
        for row in rows:
            f.write("\t".join(str(c) for c in row) + "\n")
    print("wrote %d rows" % len(rows))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
