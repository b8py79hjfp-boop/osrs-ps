#!/usr/bin/env python3
"""Generate content/combat SpecialTable.kt from docs/research/special-attacks.tsv.

Usage: python3 -I tools/wiki-import/special_attacks_kt.py <tsv> <out.kt>

One SpecialRow per weapon obj with a spec bar (cache enum 906): energy, the generic accuracy / damage multipliers and
hit count where the Wiki gives plain numbers, the defence roll, the anim and graphics, instant activation. Specials
whose numbers are formulas get 1000 / 1000 here and their behaviour from the hooks in SpecialEffects.kt (by name).
"""
import csv
import re
import sys


def lead(text, default):
    m = re.match(r"\s*x?\s*(\d+(?:\.\d+)?)(?:\s*/\s*(\d+))?", text or "")
    if not m:
        return default
    v = float(m.group(1)) / (float(m.group(2)) if m.group(2) else 1.0)
    return v


def energy(text):
    m = re.match(r"\s*(\d+)", text or "")
    return int(m.group(1)) * 10 if m else 0


def defence(text):
    t = (text or "").lower()
    for k in ("stab", "slash", "crush", "ranged", "magic"):
        if t.startswith(k):
            return f"AttackType.{k.upper()}"
    return "null"


def sym(kind, name):
    return f"{kind}.{name}" if name else "-1"


def main():
    src, out = sys.argv[1], sys.argv[2]
    rows = []
    for r in csv.DictReader(open(src), delimiter="\t"):
        acc = r["accuracy_multiplier"]
        dmg = r["damage_multiplier"]
        accuracy = 0 if acc.startswith("guaranteed") else int(round(lead(acc, 1.0) * 1000))
        damage = int(round(lead(dmg, 1.0) * 1000)) if re.match(r"\s*x?\s*\d", dmg or "") else 1000
        hits = int(lead(r["hits"], 1)) if re.match(r"\s*\d", r["hits"] or "") else 1
        style = r["style"].split(" ")[0].upper()
        if style not in ("MELEE", "RANGED", "MAGIC", "INSTANT"):
            style = "MELEE"
        instant = "true" if r["instant"].startswith("yes") else "false"
        name = r["special_name"].replace('"', "'")
        rows.append(
            f'        SpecialRow(Objs.{r["obj_symbol"]}, "{name}", {energy(r["energy_percent"])}, SpecStyle.{style}, {accuracy}, '
            f'{damage}, {hits}, {defence(r["defence_roll_against"])}, {sym("Seqs", r["seq_symbol"])}, '
            f'{sym("SpotAnims", r["spotanim_symbol"])}, {sym("SpotAnims", r["target_spotanim_symbol"])}, '
            f'{sym("SpotAnims", r["projectile_spotanim_symbol"])}, {instant}),'
        )
    with open(out, "w") as f:
        f.write(
            """@file:Suppress("ktlint:standard:max-line-length") // generated data rows

package tp.content.combat

import tp.symbols.Objs
import tp.symbols.Seqs
import tp.symbols.SpotAnims

// GENERATED by tools/wiki-import/special_attacks_kt.py from docs/research/special-attacks.tsv (cache enum 906, OSRS Wiki
// special attack pages, CC BY-NC-SA 3.0; RS Mod spec visuals, ISC). Do not edit by hand.

/** Every weapon obj with a special attack bar (docs/mechanics/special-attacks.md SP1). */
@Suppress("LargeClass", "MaxLineLength")
internal object SpecialTable {
    @Suppress("MagicNumber", "LongMethod")
    val ALL: List<SpecialRow> = listOf(
"""
            + "\n".join(rows)
            + """
    )
}
"""
        )
    print(f"wrote {len(rows)} rows to {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
