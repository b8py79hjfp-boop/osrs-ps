package tp.tools.ksp

import com.google.devtools.ksp.getAllSuperTypes
import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.ClassKind
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.KSFile
import com.google.devtools.ksp.symbol.Modifier

/**
 * Finds every concrete `tp.plugin.ContentPlugin` in the module being compiled and generates
 * `tp.content.registry.<Name>Registry : ContentRegistry` listing them, plus its `META-INF/services` entry so the server
 * finds each module's registry through `ServiceLoader` (an explicit index, not classpath scanning: DECISIONS D-023).
 * `<Name>` comes from the KSP option `tp.registry`.
 */
class RegistryProcessor(private val codegen: CodeGenerator, private val logger: KSPLogger, private val name: String) : SymbolProcessor {
    private var done = false

    override fun process(resolver: Resolver): List<KSAnnotated> {
        if (done) return emptyList()
        done = true
        val plugins =
            resolver
                .getNewFiles()
                .flatMap { it.declarations }
                .filterIsInstance<KSClassDeclaration>()
                .filter { it.isPlugin() }
                .sortedBy { it.qualifiedName?.asString() }
                .toList()
        for (p in plugins) {
            val ctor = p.primaryConstructor
            if (p.classKind != ClassKind.OBJECT && ctor != null && ctor.parameters.any { !it.hasDefault }) {
                logger.error("ContentPlugin needs a no-arg constructor", p)
            }
        }
        val files = plugins.mapNotNull { it.containingFile }.toTypedArray<KSFile>()
        val cls = "${name}Registry"
        codegen.createNewFile(Dependencies(true, *files), PACKAGE, cls).bufferedWriter().use { w ->
            w.write("package $PACKAGE\n\n")
            w.write("/** Generated by tools/ksp-registry: every ContentPlugin of this module. */\n")
            w.write("public class $cls : tp.plugin.ContentRegistry {\n")
            w.write("    override val plugins: List<tp.plugin.ContentPlugin> =\n        listOf(\n")
            for (p in plugins) {
                val q = p.qualifiedName?.asString() ?: continue
                w.write(if (p.classKind == ClassKind.OBJECT) "            $q,\n" else "            $q(),\n")
            }
            w.write("        )\n}\n")
        }
        codegen
            .createNewFileByPath(Dependencies(true, *files), "META-INF/services/tp.plugin.ContentRegistry", "")
            .bufferedWriter()
            .use { it.write("$PACKAGE.$cls\n") }
        return emptyList()
    }

    private fun KSClassDeclaration.isPlugin(): Boolean =
        Modifier.ABSTRACT !in modifiers &&
            classKind in setOf(ClassKind.CLASS, ClassKind.OBJECT) &&
            getAllSuperTypes().any { it.declaration.qualifiedName?.asString() == PLUGIN }

    private companion object {
        const val PACKAGE = "tp.content.registry"
        const val PLUGIN = "tp.plugin.ContentPlugin"
    }
}

class RegistryProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor {
        val name = environment.options["tp.registry"] ?: error("KSP option tp.registry is required")
        return RegistryProcessor(environment.codeGenerator, environment.logger, name)
    }
}
